import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "..");
const outputDir = path.join(
  repoRoot,
  "./modules/core/internal/generated/issuegraphassets",
);
const assets = [
  ["copilotPluginManifest", "issuegraph/.copilot-plugin/plugin.json"],
  ["agentSkill", "issuegraph/skills/issuegraph/SKILL.md"],
  ["agentSkillOpenAIYAML", "issuegraph/skills/issuegraph/agents/openai.yaml"],
];

const quoteGo = (value) => JSON.stringify(value);

const generatedAssets = await Promise.all(
  assets.map(async ([name, relativePath]) => {
    const content = await readFile(path.join(repoRoot, relativePath), "utf8");
    return `const ${name} = ${quoteGo(content)}`;
  }),
);

// The whole agent skill ships in the binary so `issuegraph install` can write
// SKILL.md plus commands/ and resources/. README.md, CLAUDE.md and adr/ are
// repository documentation, not skill content.
const skillRoot = path.join(repoRoot, "issuegraph/skills/issuegraph");
const skillExcluded = (rel) =>
  rel === "README.md" || rel === "CLAUDE.md" || rel.startsWith("adr/");

async function listSkillFiles(dir, prefix = "") {
  const entries = await readdir(path.join(dir, prefix), { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (skillExcluded(rel) || entry.name === ".DS_Store") continue;
    if (entry.isDirectory()) files.push(...(await listSkillFiles(dir, rel)));
    else files.push(rel);
  }
  return files;
}

const skillRels = (await listSkillFiles(skillRoot)).sort();
const skillEntries = await Promise.all(
  skillRels.map(async (rel) => {
    const content = await readFile(path.join(skillRoot, rel), "utf8");
    return `\t${quoteGo(rel)}: ${quoteGo(content)},`;
  }),
);

const generatedSource = [
  "// Code generated by scripts/generate-issuegraph-assets.mjs; DO NOT EDIT.",
  "package issuegraphassets",
  ...generatedAssets,
  "func CopilotPluginManifest() string { return copilotPluginManifest }",
  "func AgentSkill() string { return agentSkill }",
  "func AgentSkillOpenAIYAML() string { return agentSkillOpenAIYAML }",
  "var skillFiles = map[string]string{",
  ...skillEntries,
  "}",
  "// SkillFiles returns a copy of the embedded skill tree keyed by slash-separated relative path.",
  "func SkillFiles() map[string]string {",
  "\tout := make(map[string]string, len(skillFiles))",
  "\tfor k, v := range skillFiles {",
  "\t\tout[k] = v",
  "\t}",
  "\treturn out",
  "}",
  "",
].join("\n");

await mkdir(outputDir, { recursive: true });
await writeFile(path.join(outputDir, "assets_gen.go"), generatedSource);
