import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, "..");
const outputDir = path.join(
  repoRoot,
  "./modules/core/internal/generated/issuegraphassets",
);
const assets = [
  ["copilotPluginManifest", "issuegraph/.copilot-plugin/plugin.json"],
  ["agentSkill", "issuegraph/skills/issuegraph/SKILL.md"],
  ["agentSkillOpenAIYAML", "issuegraph/skills/issuegraph/agents/openai.yaml"],
];

const quoteGo = (value) => JSON.stringify(value);

const generatedAssets = await Promise.all(
  assets.map(async ([name, relativePath]) => {
    const content = await readFile(path.join(repoRoot, relativePath), "utf8");
    return `const ${name} = ${quoteGo(content)}`;
  }),
);

const generatedSource = [
  "// Code generated by scripts/generate-issuegraph-assets.mjs; DO NOT EDIT.",
  "package issuegraphassets",
  ...generatedAssets,
  "func CopilotPluginManifest() string { return copilotPluginManifest }",
  "func AgentSkill() string { return agentSkill }",
  "func AgentSkillOpenAIYAML() string { return agentSkillOpenAIYAML }",
  "",
].join("\n");

await mkdir(outputDir, { recursive: true });
await writeFile(path.join(outputDir, "assets_gen.go"), generatedSource);
